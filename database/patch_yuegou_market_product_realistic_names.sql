UPDATE twenty_mall_product p
JOIN tmp_yuegou_product_names n ON n.product_no = p.product_no
JOIN twenty_mall_account ma ON ma.id = p.merchant_account_id
SET p.product_name = n.product_name,
    p.category = n.category,
    p.description = CONCAT(n.product_name, '，由', ma.display_name, '提供。商品信息已按真实图片类目整理，支持平台订单同步、售后申请与评价分析。'),
    p.product_image_url = CONCAT('/assets/products/yuegou-market/yuegou-', SUBSTRING(n.product_no, 6, 2), '-', SUBSTRING(n.product_no, 9, 2), '.png'),
    p.updated_at = NOW()
WHERE ma.platform_code = 'YUEGOU_MARKET';

UPDATE twenty_mall_order_item oi
JOIN twenty_mall_product p ON p.id = oi.product_id
JOIN tmp_yuegou_product_names n ON n.product_no = p.product_no
JOIN twenty_mall_account ma ON ma.id = p.merchant_account_id
